// Language switcher logic
(function() {
  const STORAGE_KEY = 'securecall_lang';
  const DEFAULT_LANG = 'en';

  function getCurrentLang() {
    return localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
  }

  function setLang(lang) {
    if (!I18N[lang]) return;
    localStorage.setItem(STORAGE_KEY, lang);
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (I18N[lang][key]) el.innerHTML = I18N[lang][key];
    });
    // Update active button
    document.querySelectorAll('.lang-btn').forEach(b => {
      b.classList.toggle('active', b.getAttribute('data-lang') === lang);
    });
    // Privacy page language blocks (if present)
    document.querySelectorAll('.lang-content').forEach(el => {
      el.style.display = el.getAttribute('data-lang') === lang ? 'block' : 'none';
    });
  }

  function createSwitcher() {
    const langs = [
      { code: 'en', label: 'EN' }, { code: 'de', label: 'DE' },
      { code: 'el', label: '\u0395\u039b' }, { code: 'it', label: 'IT' },
      { code: 'es', label: 'ES' }, { code: 'ru', label: 'RU' },
      { code: 'zh', label: '\u4e2d\u6587' }
    ];
    const current = getCurrentLang();
    const container = document.createElement('div');
    container.className = 'lang-switcher-nav';
    container.innerHTML = langs.map(l =>
      `<button class="lang-btn${l.code === current ? ' active' : ''}" data-lang="${l.code}">${l.label}</button>`
    ).join('');
    container.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', () => setLang(btn.getAttribute('data-lang')));
    });
    return container;
  }

  // Inject switcher into nav and apply saved language
  document.addEventListener('DOMContentLoaded', () => {
    const navLinks = document.getElementById('navLinks');
    if (navLinks) {
      const downloadBtn = navLinks.querySelector('.nav-cta');
      const switcher = createSwitcher();
      if (downloadBtn) navLinks.insertBefore(switcher, downloadBtn);
      else navLinks.appendChild(switcher);
    }
    const lang = getCurrentLang();
    if (lang !== DEFAULT_LANG) setLang(lang);
  });
})();
